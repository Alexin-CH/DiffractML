"""Emit the remote MEEP manifest for the generalisation dataset.

Default job set (``B``): 8 geometries x {0, 30, 60} deg x {s, p}, 16 wavelengths.

Cost model: a normal-incidence job is **one** broadband simulation, while an
oblique job runs **one narrowband simulation per wavelength** (a fixed phase
ramp only matches one frequency).  The manifest therefore reports simulations,
not just jobs.

The shell script parallelises independent jobs with ``xargs -P``; each job is
already internally sequential over wavelengths.

Example
-------
    python scripts/reference_manifest.py --python ~/miniconda3/envs/meep-v7/bin/python
    JOBS=3 bash reports/m2/remote_manifest.sh
"""

from __future__ import annotations

import argparse
import json
import os

_HERE = os.path.dirname(os.path.abspath(__file__))

SUBSET = [0, 3, 5, 9, 13, 15, 19, 22]
RESONANT = list(range(8))
ANGLES = [0, 30, 60]


def jobs(sets):
    """One job per (geometry, pol, angle) so runs are small and resumable."""
    out = []

    def add(tag, spec_set, specs, angles):
        for idx in specs:
            for pol in ("s", "p"):
                for angle in angles:
                    out.append(dict(set=tag, spec_set=spec_set, spec=idx,
                                    pol=pol, angle=angle))

    if "A" in sets:
        add("A", "m2", range(24), [0])
    if "B" in sets:
        add("B", "m2", SUBSET, ANGLES)
    if "C" in sets:
        add("C", "resonant", RESONANT, [30, 60])
    return out


def simulations(job, n_freq):
    """One broadband run at normal incidence, ``n_freq`` narrowband otherwise."""
    return 1 if abs(job["angle"]) < 1e-9 else n_freq


def command(job, out_dir, resolution, python, n_freq):
    return (
        f"{python} scripts/generate_m2_references.py "
        f"--spec-set {job['spec_set']} --specs {job['spec']} "
        f"--pol {job['pol']} --angle {job['angle']} "
        f"--resolution {resolution} --n-freq {n_freq} --out-dir {out_dir}"
    )


def main(argv=None):
    p = argparse.ArgumentParser(description="Emit the remote MEEP manifest")
    p.add_argument("--sets", nargs="+", default=["B"],
                   choices=["A", "B", "C"])
    p.add_argument("--resolution", type=float, default=140.0)
    p.add_argument("--n-freq", type=int, default=16)
    p.add_argument("--python", default="python",
                   help="interpreter the remote job should use")
    p.add_argument("--jobs", type=int, default=3,
                   help="parallel workers in the emitted runner")
    p.add_argument("--minutes-normal", type=float, default=2.0)
    p.add_argument("--minutes-oblique", type=float, default=3.0)
    p.add_argument("--out-dir", default="reports/m2/data140")
    p.add_argument("--shell", default="reports/m2/remote_manifest.sh")
    p.add_argument("--jobs-file", default="reports/m2/remote_jobs.txt")
    p.add_argument("--json-out", default="reports/m2/remote_manifest.json")
    a = p.parse_args(argv)

    selected = jobs(a.sets)
    cmds = [command(j, a.out_dir, a.resolution, a.python, a.n_freq)
            for j in selected]

    os.makedirs(os.path.dirname(os.path.abspath(a.shell)), exist_ok=True)
    with open(a.jobs_file, "w") as fh:
        fh.write("\n".join(cmds) + "\n")

    runner = [
        "#!/usr/bin/env bash",
        "# Generated by scripts/reference_manifest.py",
        f"# resolution={a.resolution}, out-dir={a.out_dir}, "
        f"n_freq={a.n_freq}",
        "set -euo pipefail",
        'cd "$(dirname "$0")/../.."',
        'JOBS="${JOBS:-%d}"' % a.jobs,
        "export OMP_NUM_THREADS=1",
        'LOG="reports/m2/manifest_run.log"',
        'T0=$(date +%s)',
        f'echo "[manifest] start $(date -Is) · $JOBS workers · '
        f'{len(selected)} jobs · {a.n_freq} lambda for oblique" | tee -a "$LOG"',
        f'xargs -d "\\n" -P "$JOBS" -I CMD bash -c "CMD" < "{a.jobs_file}" '
        f'2>&1 | tee -a "$LOG"',
        'T1=$(date +%s)',
        'echo "[manifest] done $(date -Is) · elapsed $((T1-T0)) s" | tee -a "$LOG"',
    ]
    with open(a.shell, "w") as fh:
        fh.write("\n".join(runner) + "\n")
    os.chmod(a.shell, 0o755)

    total_sims = 0
    entries = []
    for j, cmd in zip(selected, cmds):
        sims = simulations(j, a.n_freq)
        total_sims += sims
        entries.append({**j, "sims": sims, "command": cmd})
    minutes = sum(sims * (a.minutes_oblique if abs(j["angle"]) > 1e-9
                          else a.minutes_normal)
                  for j, sims in zip(selected,
                                     [e["sims"] for e in entries]))
    manifest = {
        "resolution": a.resolution,
        "n_freq": a.n_freq,
        "out_dir": a.out_dir,
        "total_sims": total_sims,
        "serial_hours": minutes / 60.0,
        "parallel_jobs": a.jobs,
        "parallel_hours": minutes / 60.0 / max(1, a.jobs),
        "jobs": entries,
    }
    with open(a.json_out, "w") as fh:
        json.dump(manifest, fh, indent=2)

    print(f"{len(selected)} jobs, {total_sims} MEEP simulations "
          f"({a.n_freq} lambda per oblique job, 1 broadband at 0 deg)")
    print(f"serial estimate ~{minutes / 60:.1f} h at res={a.resolution:g}; "
          f"~{minutes / 60 / max(1, a.jobs):.1f} h with JOBS={a.jobs}")
    print(f"wrote {a.shell}")
    print(f"wrote {a.jobs_file}")
    print(f"wrote {a.json_out}")


if __name__ == "__main__":
    main()
