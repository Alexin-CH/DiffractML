"""Emit the remote MEEP manifest for the generalisation datasets.

Writes a shell script (one command per job) and a JSON manifest.  The jobs are:

``A``  p-pol, normal incidence, 24 existing geometries (res=140)
``B``  oblique, 8 existing geometries x {0,30,60} deg x {s,p} (res=140)
``C``  Rayleigh-rich, 8 small-period 10-ridge geometries x {30,60} deg x {s,p}

Set B regenerates 0 deg s-pol at 140 so the oblique experiment is internally
consistent (the original M2 set is at 105).

Example
-------
    python scripts/reference_manifest.py --sets A B C \
        --out-dir reports/m2/data140 --shell reports/m2/remote_manifest.sh
"""

from __future__ import annotations

import argparse
import json
import os

_HERE = os.path.dirname(os.path.abspath(__file__))

SUBSET = [0, 3, 5, 9, 13, 15, 19, 22]
RESONANT = list(range(8))
ANGLES = [0, 30, 60]


def jobs():
    out = []
    # A: p-pol normal, all 24
    out.append(dict(set="A", spec_set="m2", specs=list(range(24)),
                    pol="p", angle=0))
    # B: oblique on the 8-geometry subset, both pols, 0/30/60
    for pol in ("s", "p"):
        for angle in ANGLES:
            out.append(dict(set="B", spec_set="m2", specs=SUBSET,
                            pol=pol, angle=angle))
    # C: Rayleigh-rich, both pols, 30/60
    for pol in ("s", "p"):
        for angle in (30, 60):
            out.append(dict(set="C", spec_set="resonant", specs=RESONANT,
                            pol=pol, angle=angle))
    return out


def command(job, out_dir, resolution):
    specs = " ".join(str(i) for i in job["specs"])
    return (
        "python scripts/generate_m2_references.py "
        f"--spec-set {job['spec_set']} --specs {specs} "
        f"--pol {job['pol']} --angle {job['angle']} "
        f"--resolution {resolution} --out-dir {out_dir}"
    )


def main(argv=None):
    p = argparse.ArgumentParser(description="Emit the remote MEEP manifest")
    p.add_argument("--sets", nargs="+", default=["A", "B", "C"],
                   choices=["A", "B", "C"])
    p.add_argument("--resolution", type=float, default=140.0)
    p.add_argument("--out-dir", default="reports/m2/data140")
    p.add_argument("--shell", default="reports/m2/remote_manifest.sh")
    p.add_argument("--json-out", default="reports/m2/remote_manifest.json")
    a = p.parse_args(argv)

    selected = [j for j in jobs() if j["set"] in a.sets]
    lines = [
        "#!/usr/bin/env bash",
        "# Generated by scripts/reference_manifest.py",
        f"# resolution={a.resolution}, out-dir={a.out_dir}",
        "set -euo pipefail",
        "",
    ]
    for j in selected:
        lines.append(f"# set {j['set']}: {len(j['specs'])} specs, "
                     f"{j['pol']}-pol, {j['angle']} deg")
        lines.append(command(j, a.out_dir, a.resolution))
        lines.append("")

    os.makedirs(os.path.dirname(os.path.abspath(a.shell)), exist_ok=True)
    with open(a.shell, "w") as fh:
        fh.write("\n".join(lines))
    os.chmod(a.shell, 0o755)

    manifest = {
        "resolution": a.resolution,
        "out_dir": a.out_dir,
        "jobs": [
            {**j, "runs": len(j["specs"]),
             "command": command(j, a.out_dir, a.resolution)}
            for j in selected
        ],
    }
    with open(a.json_out, "w") as fh:
        json.dump(manifest, fh, indent=2)

    total = sum(len(j["specs"]) for j in selected)
    print(f"{len(selected)} jobs, {total} MEEP runs")
    print(f"wrote {a.shell}")
    print(f"wrote {a.json_out}")
    est_min = total * (1.0 if a.resolution <= 105 else 2.0)
    print(f"serial estimate: ~{est_min / 60:.1f} h at res={a.resolution:g} "
          f"(÷ workers when parallelised)")


if __name__ == "__main__":
    main()
