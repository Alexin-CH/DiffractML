"""Emit the remote MEEP manifest for the generalisation datasets.

Writes three files next to each other:

- ``remote_manifest.sh``  one command per line, run sequentially
- ``remote_jobs.txt``     the same commands, consumed by ``run_parallel.sh``
- ``run_parallel.sh``     ``xargs -P $JOBS`` runner (use inside tmux on the GPU box)

Jobs:

``A``  p-pol, normal incidence, 24 existing geometries
``B``  8 existing geometries x {0,30,60} deg x {s,p}   (default)
``C``  Rayleigh-rich, 8 small-period 10-ridge geometries x {30,60} deg x {s,p}

Cost model
----------
At normal incidence one broadband MEEP run yields all wavelengths.  At oblique
incidence ``run_grating`` needs one narrowband run **per wavelength**, and uses
a wider cell (``pad=1.5``, ``air_above=1.0``).  The manifest therefore counts
simulations, not jobs, and estimates both.

Example
-------
    python scripts/reference_manifest.py --sets B --n-freq 16 --jobs 2
    # -> 6 jobs, 528 reference points, 1056 FDTD runs,
    #    ~56 h serial, ~28 h on 2 workers
"""

from __future__ import annotations

import argparse
import json
import os

_HERE = os.path.dirname(os.path.abspath(__file__))

SUBSET = [0, 3, 5, 9, 13, 15, 19, 22]
RESONANT = list(range(8))
ANGLES = [0, 30, 60]


def jobs():
    out = []
    out.append(dict(set="A", spec_set="m2", specs=list(range(24)),
                    pol="p", angle=0))
    for pol in ("s", "p"):
        for angle in ANGLES:
            out.append(dict(set="B", spec_set="m2", specs=SUBSET,
                            pol=pol, angle=angle))
    for pol in ("s", "p"):
        for angle in (30, 60):
            out.append(dict(set="C", spec_set="resonant", specs=RESONANT,
                            pol=pol, angle=angle))
    return out


def sims_per_job(job, n_freq: int) -> int:
    """Normal incidence is one broadband run; oblique is one run per λ."""
    return 1 if abs(job["angle"]) < 1e-9 else n_freq


def command(job, out_dir, resolution, n_freq):
    specs = " ".join(str(i) for i in job["specs"])
    return (
        "python scripts/generate_m2_references.py "
        f"--spec-set {job['spec_set']} --specs {specs} "
        f"--pol {job['pol']} --angle {job['angle']} --n-freq {n_freq} "
        f"--resolution {resolution} --out-dir {out_dir}"
    )


RUNNER = """#!/usr/bin/env bash
# Parallel MEEP runner generated by scripts/reference_manifest.py.
# Run inside tmux from anywhere:  bash v7-finite-grating/reports/m2/run_parallel.sh
set -uo pipefail
cd "$(dirname "$0")/../.."
JOBS="${JOBS:-%(jobs)d}"
export OMP_NUM_THREADS=1
echo "[runner] start $(date -Is)  jobs=$JOBS  cwd=$(pwd)"
xargs -a reports/m2/remote_jobs.txt -d '\\n' -P "$JOBS" -I CMD \\
    bash -c 'echo "[start] $(date +%%H:%%M:%%S) CMD"; CMD; echo "[done ] $(date +%%H:%%M:%%S) CMD"'
echo "[runner] done  $(date -Is)"
"""


def main(argv=None):
    p = argparse.ArgumentParser(description="Emit the remote MEEP manifest")
    p.add_argument("--sets", nargs="+", default=["B"],
                   choices=["A", "B", "C"])
    p.add_argument("--resolution", type=float, default=140.0)
    p.add_argument("--n-freq", type=int, default=16)
    p.add_argument("--jobs", type=int, default=2,
                   help="parallel MEEP processes (2 on the 4-thread remote)")
    p.add_argument("--min-normal", type=float, default=6.4,
                   help="minutes per normal reference point (control + structure)")
    p.add_argument("--min-oblique", type=float, default=6.4,
                   help="minutes per oblique reference point (control + structure)")
    p.add_argument("--runs-per-ref", type=int, default=2,
                   help="FDTD runs per reference point (control + structure)")
    p.add_argument("--out-dir", default="reports/m2/data140")
    p.add_argument("--shell", default="reports/m2/remote_manifest.sh")
    p.add_argument("--jobs-file", default="reports/m2/remote_jobs.txt")
    p.add_argument("--runner", default="reports/m2/run_parallel.sh")
    p.add_argument("--json-out", default="reports/m2/remote_manifest.json")
    a = p.parse_args(argv)

    selected = [j for j in jobs() if j["set"] in a.sets]
    commands = [command(j, a.out_dir, a.resolution, a.n_freq) for j in selected]

    for path in (a.shell, a.jobs_file, a.runner, a.json_out):
        os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)

    with open(a.shell, "w") as fh:
        fh.write("#!/usr/bin/env bash\nset -uo pipefail\n\n")
        for j, cmd in zip(selected, commands):
            fh.write(f"# set {j['set']}: {len(j['specs'])} specs, "
                     f"{j['pol']}-pol, {j['angle']} deg\n{cmd}\n\n")
    os.chmod(a.shell, 0o755)

    with open(a.jobs_file, "w") as fh:
        fh.write("\n".join(commands) + "\n")

    with open(a.runner, "w") as fh:
        fh.write(RUNNER % {"jobs": a.jobs})
    os.chmod(a.runner, 0o755)

    total_sims = sum(sims_per_job(j, a.n_freq) * len(j["specs"])
                     for j in selected)
    normal_sims = sum(sims_per_job(j, a.n_freq) * len(j["specs"])
                      for j in selected if abs(j["angle"]) < 1e-9)
    oblique_sims = total_sims - normal_sims
    serial_min = normal_sims * a.min_normal + oblique_sims * a.min_oblique

    manifest = {
        "resolution": a.resolution,
        "n_freq": a.n_freq,
        "out_dir": a.out_dir,
        "jobs": [
            {**j, "specs": list(j["specs"]),
             "sims": sims_per_job(j, a.n_freq) * len(j["specs"]),
             "command": cmd}
            for j, cmd in zip(selected, commands)
        ],
        "totals": {
            "jobs": len(selected),
            "reference_points": total_sims,
            "normal_reference_points": normal_sims,
            "oblique_reference_points": oblique_sims,
            "fdtd_runs": total_sims * a.runs_per_ref,
            "runs_per_ref": a.runs_per_ref,
            "serial_hours": serial_min / 60.0,
            "parallel_hours": serial_min / 60.0 / max(1, a.jobs),
        },
    }
    with open(a.json_out, "w") as fh:
        json.dump(manifest, fh, indent=2)

    print(f"{len(selected)} jobs, {total_sims} reference points "
          f"({normal_sims} normal + {oblique_sims} oblique)")
    print(f"FDTD runs  : {total_sims * a.runs_per_ref} "
          f"({a.runs_per_ref} per point: control + structure)")
    print(f"serial     : ~{serial_min / 60:.1f} h at res={a.resolution:g}")
    print(f"parallel   : ~{serial_min / 60 / max(1, a.jobs):.1f} h "
          f"on {a.jobs} workers")
    for path in (a.shell, a.jobs_file, a.runner, a.json_out):
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
